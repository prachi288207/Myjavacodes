package com.java;

public class user {
	int id;
	String name;
	float fees;
	public user(int id,String name, float fees) {
		this.id=id;
		this.name=name;
		this.fees=fees;					
	}
	public int getId() {
		return id;
	}
	public String getName() {
		return name;
	}
	public float getFees() {
		return fees;
	}
	
	
}
